// Reproduce local learning texts without any network or installed dependencies.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const books = {
  "4-lower": ["421", "4年级下册"],
  "5-upper": ["511", "5年级上册"],
  "5-lower": ["521", "5年级下册"],
  "6-upper": ["611", "6年级上册"],
  "6-lower": ["621", "6年级下册"]
};
// Isolated-character readings from pinyin-pro 3.18.2 (already used by index.html).
// These characters have no reading in the matching pinned source book.
// Polyphonic readings are dictionary defaults, not a claim about lesson context.
const dictionary = {
  笼: "lóng", 投: "tóu", 哩: "lī", 鞋: "xié", 溜: "liū", 孙: "sūn",
  黎: "lí", 晕: "yūn", 愈: "yù", 旷: "kuàng", 怡: "yí", 逸: "yì",
  尾: "wěi", 窥: "kuī", 射: "shè", 瞪: "dèng", 蒜: "suàn", 皎: "jiǎo"
};

async function transformedText(bookId, dataset) {
  const context = {
    URLSearchParams, Response, console,
    window: {
      location: { search: `?book=${bookId}` },
      fetch: async () => ({ ok: true, json: async () => dataset })
    }
  };
  vm.createContext(context);
  // Use existing runtime adapter unchanged to retain its vocabulary priorities.
  // Select a source-backed book ID so that the generated-text passthrough does
  // not run during this build-time transformation.
  context.window.location.search = "?book=1-upper";
  vm.runInContext(fs.readFileSync(path.join(root, "writing-table-support.js"), "utf8"), context);
  return (await context.window.fetch("生字数据.txt")).text();
}

function scopeFor(label) {
  return fs.readFileSync(path.join(root, `生字数据_${label}.txt`), "utf8")
    .split(/\r?\n/).map(line => line.trim())
    .filter(line => line && !line.startsWith("#"));
}

async function buildBook(bookId) {
  const [source, label] = books[bookId];
  const dataset = JSON.parse(fs.readFileSync(path.join(root, `curriculum/renjiao/${source}.json`), "utf8"));
  const volume = dataset.grades[0].volumes[0];
  const scope = scopeFor(label);
  const allowed = new Set(scope);
  if (scope.length !== allowed.size) throw new Error(`Duplicate local writing-table character: ${bookId}`);
  const emitted = new Set();
  const output = ["# Generated by scripts/build-grade-4-6.js; do not edit.",
    "# Character scope: existing local 写字表. Lesson/word metadata: pinned shukong-app source."];
  let heading = "";
  let headingWritten = false;
  for (const line of (await transformedText(bookId, dataset)).split("\n")) {
    if (line.startsWith("[")) { heading = line; headingWritten = false; continue; }
    const character = line.split("|")[0];
    if (!allowed.has(character) || emitted.has(character)) continue;
    if (!headingWritten) { output.push(heading); headingWritten = true; }
    output.push(line);
    emitted.add(character);
  }
  const indexed = (volume.writing || []).flatMap(entry => entry.characters || [])
    .concat((volume.recognition || []).flatMap(entry => entry.characters || []),
      (volume.words || []).flatMap(entry => entry.characters || []).flat());
  const missing = scope.filter(character => !emitted.has(character));
  if (missing.length) output.push("[写字表补充（课次待核对）]");
  for (const character of missing) {
    const pinyin = indexed.find(item => item.character === character && item.pinyin)?.pinyin || dictionary[character];
    if (!pinyin) throw new Error(`No sourced reading: ${bookId}/${character}`);
    output.push(`${character}|${pinyin}|${character}|${pinyin}|本地写字表生字（课次与组词待核对）`);
  }
  return output.join("\n") + "\n";
}

async function main() {
  const generated = await Promise.all(Object.keys(books).map(async bookId => [bookId, await buildBook(bookId)]));
  if (process.argv.includes("--patch")) {
    // The caller applies this using apply_patch; this script never writes files.
    console.log("*** Begin Patch");
    for (const [bookId, text] of generated) {
      console.log(`*** Add File: ${path.join(root, `curriculum/renjiao/${bookId}.txt`).replace(/\\/g, "/")}`);
      console.log(text.trimEnd().split("\n").map(line => "+" + line).join("\n"));
    }
    console.log("*** End Patch");
  } else {
    for (const [bookId, text] of generated) {
      const actual = fs.readFileSync(path.join(root, `curriculum/renjiao/${bookId}.txt`), "utf8");
      if (actual.replace(/\r\n/g, "\n") !== text) throw new Error(`${bookId}: generated curriculum has drifted`);
      console.log(`${bookId}: reproducible local curriculum PASS`);
    }
  }
}
if (require.main === module) main().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { books, buildBook, scopeFor };
